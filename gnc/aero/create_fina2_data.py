# Write Excel spreadsheets matching stage_xlsx_to_dat.m layout
# ============================================================
def write_xlsx(path, stage_name, scalars, mach, alpha, tables, roll_defl=None, roll_blocks=None, roll_names=None):
    """
    tables: list of (block_name, row_axis, data_2d)
    roll_blocks: list of (block_name, data_2d) if any
    """
    if not HAS_OPENPYXL:
        print(f'  SKIP {path} (openpyxl not available)')
        return

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = 'Aero'

    # Row 1: stage name
    ws.cell(row=1, column=1, value=stage_name)

    # Row 2: scalar labels, Row 3: scalar values
    for i, (name, val) in enumerate(scalars):
        ws.cell(row=2, column=i+1, value=name)
        ws.cell(row=3, column=i+1, value=val)

    # Row 4: 'mach' + mach values
    ws.cell(row=4, column=1, value='mach')
    for j, m in enumerate(mach):
        ws.cell(row=4, column=j+2, value=m)

    # Write each table block
    row = 5  # start after mach row
    for block_name, row_axis, data in tables:
        # blank row separator
        row += 1
        # block header
        ws.cell(row=row, column=1, value=block_name)
        row += 1
        # data rows
        for i, ax_val in enumerate(row_axis):
            ws.cell(row=row, column=1, value=ax_val)
            for j, val in enumerate(data[i]):
                ws.cell(row=row, column=j+2, value=val)
            row += 1

    # Roll blocks
    if roll_blocks:
        for block_name, data in roll_blocks:
            row += 1
            ws.cell(row=row, column=1, value=block_name)
            row += 1
            for i, ax_val in enumerate(alpha):
                ws.cell(row=row, column=1, value=ax_val)
                for j, val in enumerate(data[i]):
                    ws.cell(row=row, column=j+2, value=val)
                row += 1

    wb.save(path)
    print(f'  wrote {path}')


