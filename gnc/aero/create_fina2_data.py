def num_row(v):
    return ' '.join(f'{x:.17g}' for x in v)

def write_table2(f, name, rowax, colax, data):
    f.write(f'TABLE2 {name} {len(data)} {len(data[0])}\n')
    f.write(f'ROWAXIS {num_row(rowax)}\n')
    f.write(f'COLAXIS {num_row(colax)}\n')
    for row in data:
        f.write(num_row(row) + '\n')
    f.write('END\n\n')

def write_table3_roll(f, target_name, alpha, mach_n, roll_defl, roll_blocks):
    """Write a TABLE3 for the rolling moment (deflection=0 is all zeros)."""
    na = len(alpha)
    nw = len(roll_blocks[0][0])  # number of Mach points used
    nd = len(roll_defl)
    f.write(f'TABLE3 {target_name} {na} {nw} {nd}\n')
    f.write(f'AXIS1 {num_row(alpha)}\n')
    f.write(f'AXIS2 {num_row(mach_n)}\n')
    f.write(f'AXIS3 {num_row(roll_defl)}\n')
    for a in range(na):
        for m in range(nw):
            v = [0.0]  # deflection 0 -> zero
            for blk in roll_blocks:
                v.append(blk[a][m])
            f.write(num_row(v) + '\n')
    f.write('END\n\n')


